from __future__ import annotations

import h5py

from twingr00t_lab.mimic_results import summarize_fixed_mimic_trials


def test_summarize_failed_fixed_mimic_trials(tmp_path) -> None:
    trials = []
    for seed in (1, 2, 3):
        dataset = tmp_path / f"seed{seed}.hdf5"
        with h5py.File(dataset, "w") as handle:
            data = handle.create_group("data")
            data.attrs["total"] = 0
        log = tmp_path / f"seed{seed}.log"
        log.write_text(
            "[TwinGR00T] Mimic fixed-attempt mode\n"
            f"[TwinGR00T] Mimic seed: {seed}\n"
            "0/1 (0.0%) successful demos generated by mimic\n",
            encoding="utf-8",
        )
        trials.append((seed, dataset, log))

    result = summarize_fixed_mimic_trials(trials)
    assert result["attempts"] == 3
    assert result["successes"] == 0
    assert result["gate_at_least_1_of_3_pass"] is False
    assert result["direct_retargeting_supported"] is False
