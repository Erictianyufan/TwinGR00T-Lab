#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

PYTHON_BIN="${PYTHON_BIN:-/home/ubuntu/env_robotwin/bin/python}"
SOURCE_DATASET="${SOURCE_DATASET:-datasets/g1_official/arena_g1_loco_manipulation_dataset_annotated.hdf5}"
SCENE_USD="${TWINGR00T_SCENE_USD:-$ROOT_DIR/assets/upstream/galileo_locomanip.usd}"
CARGO_USD="${TWINGR00T_CARGO_USD:-$ROOT_DIR/assets/serving_plate.usda}"
SUPPORT_USD="${TWINGR00T_CARGO_SUPPORT_USD:-$ROOT_DIR/assets/g1_plate_table_support.usda}"

# candidate_name local_x local_z seed
CANDIDATES=(
  "x075_z030 -0.075 0.030 21"
  "x075_z060 -0.075 0.060 22"
  "x110_z030 -0.110 0.030 23"
  "x110_z060 -0.110 0.060 24"
  "x145_z030 -0.145 0.030 25"
  "x145_z060 -0.145 0.060 26"
)

mkdir -p datasets/g1_plate/sweep logs results/g1/sweep

for spec in "${CANDIDATES[@]}"; do
  read -r name offset_x offset_z seed <<<"$spec"
  source_output="datasets/g1_plate/sweep/source_${name}.hdf5"
  output="datasets/g1_plate/sweep/${name}_seed${seed}.hdf5"
  log="logs/E2c_${name}_seed${seed}.log"

  if [[ ! -f "$source_output" ]]; then
    "$PYTHON_BIN" scripts/adapt_g1_plate_seed.py \
      "$SOURCE_DATASET" "$source_output" \
      --local-offset-xyz "$offset_x" 0 "$offset_z"
  fi

  CUDA_VISIBLE_DEVICES=0 \
  TWINGR00T_SCENE_USD="$SCENE_USD" \
  TWINGR00T_SCENE_POSE_XYZ=4.42,1.4008,-0.795 \
  TWINGR00T_CARGO_USD="$CARGO_USD" \
  TWINGR00T_CARGO_SCALE=1,1,1 \
  TWINGR00T_CARGO_POSE_XYZ=0.58,0,0.076 \
  TWINGR00T_CARGO_SUPPORT_USD="$SUPPORT_USD" \
  TWINGR00T_ROBOT_POSE_XYZ=0,0,0 \
  TWINGR00T_MIMIC_GUARANTEE=0 \
  TWINGR00T_MIMIC_KEEP_FAILED=1 \
  TWINGR00T_MIMIC_SEED="$seed" \
  PYTHONUNBUFFERED=1 \
    "$PYTHON_BIN" -u scripts/generate_g1_plate_dataset.py \
      --headless --mimic \
      --input_file "$source_output" \
      --output_file "$output" \
      --generation_num_trials 1 --num_envs 1 --device cpu \
      galileo_g1_locomanip_pick_and_place \
      --object brown_box --embodiment g1_wbc_pink >"$log" 2>&1

  if grep -q "1/1 (100.0%) successful demos generated by mimic" "$log"; then
    printf 'SUCCESS %s seed=%s output=%s\n' "$name" "$seed" "$output"
    exit 0
  fi

  failed="${output%.hdf5}_failed.hdf5"
  "$PYTHON_BIN" scripts/audit_g1_mimic_failure.py "$failed" \
    --output "results/g1/sweep/${name}_seed${seed}_failure.json"
done

printf 'NO_SUCCESS tested=%s\n' "${#CANDIDATES[@]}"
exit 2
