"""Validate and summarize fixed-attempt Isaac Lab Mimic trials."""

from __future__ import annotations

import hashlib
import re
from pathlib import Path

RESULT_RE = re.compile(r"(?P<successes>\d+)/(?P<attempts>\d+) .*successful demos generated by mimic")


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def summarize_fixed_mimic_trials(trials: list[tuple[int, Path, Path]]) -> dict:
    try:
        import h5py
    except ImportError as exc:  # pragma: no cover
        raise RuntimeError("Install the data extra: pip install -e '.[data]'") from exc

    if not trials:
        raise ValueError("At least one trial is required")
    if len({seed for seed, _, _ in trials}) != len(trials):
        raise ValueError("Duplicate Mimic seeds")

    rows = []
    for seed, dataset_path, log_path in trials:
        log = log_path.read_text(encoding="utf-8", errors="replace")
        if "Mimic fixed-attempt mode" not in log:
            raise ValueError(f"Seed {seed}: not a fixed-attempt run")
        if f"Mimic seed: {seed}" not in log and seed != 1:
            raise ValueError(f"Seed {seed}: seed marker missing from log")
        matches = list(RESULT_RE.finditer(log))
        if len(matches) != 1:
            raise ValueError(f"Seed {seed}: expected one Mimic result line, found {len(matches)}")
        successes = int(matches[0].group("successes"))
        attempts = int(matches[0].group("attempts"))
        with h5py.File(dataset_path, "r") as handle:
            exported = len(handle["data"])
            exported_frames = int(handle["data"].attrs.get("total", 0))
        if exported != successes:
            raise ValueError(f"Seed {seed}: exported episodes {exported} != logged successes {successes}")
        rows.append(
            {
                "seed": seed,
                "attempts": attempts,
                "successes": successes,
                "exported_episodes": exported,
                "exported_frames": exported_frames,
                "dataset": str(dataset_path),
                "dataset_sha256": _sha256(dataset_path),
                "log": str(log_path),
                "log_sha256": _sha256(log_path),
            }
        )

    total_attempts = sum(row["attempts"] for row in rows)
    total_successes = sum(row["successes"] for row in rows)
    return {
        "schema_version": 1,
        "condition": "brown_box_annotation_retargeted_to_serving_plate",
        "protocol_valid": True,
        "seeds": [row["seed"] for row in rows],
        "attempts": total_attempts,
        "successes": total_successes,
        "success_rate": total_successes / total_attempts,
        "gate_at_least_1_of_3_pass": len(rows) >= 3 and total_successes >= 1,
        "direct_retargeting_supported": total_successes > 0,
        "trials": rows,
    }
